/**
 * The shape every locale must have, with the literal values widened to
 * `string`. Declaring `const en: Translations` therefore fails to compile if
 * a key is missing, and fails again if one is invented -- excess property
 * checking catches the second. That is the parity guard, and it runs on every
 * typecheck rather than only when a test remembers to look.
 */
type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };

export type Translations = Widen<typeof es>;
